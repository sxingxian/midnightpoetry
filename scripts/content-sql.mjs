// Builds the content migrations from content/guides/*.json.
// Run: node scripts/content-sql.mjs   (tests/content.test.ts validates the JSON against the block schema)
//
// A migration runs once per database, so content that has already shipped keeps its own
// migration file, generated from a frozen copy of the JSON it shipped with (content/guides/frozen/).
//   - A new product gets a new entry here (and a new, later migration) — never add it to a migration
//     that has already been applied.
//   - Updating a product's guides later gets a new migration with mode "update": it adds missing guides
//     and replaces the ones that nobody has edited in the admin (updated_by is null), so an editor's
//     changes are never overwritten, and every replaced version is kept in the guide's revision history.
import { readFileSync, writeFileSync } from "node:fs";

export const CONTENT_MIGRATIONS = {
  "supabase/migrations/20261024000300_studio_content.sql": { title: "Zyra and Zeno", files: ["zeno.json", "zyra.json"] },
  "supabase/migrations/20261025000100_zora_content.sql": { title: "Zora", files: ["zora.json"] },
  "supabase/migrations/20261028000100_zotikos_content.sql": { title: "Zotikos", files: ["frozen/zotikos-2026-10-28.json"] },
  "supabase/migrations/20261102000100_zotikos_guides_update.sql": { title: "Zotikos (updated guides)", files: ["frozen/zotikos-2026-11-02.json"], mode: "update" },
  "supabase/migrations/20261102000200_zotikos_insights_guides.sql": { title: "Zotikos (Insights, checks, picture and Pro guides)", files: ["zotikos.json"], mode: "update" },
};
const q = (s) => {
  const v = String(s);
  if (v.includes("$c$")) throw new Error("Content may not contain $c$");
  return `$c$${v}$c$`;
};

for (const [OUT, { title, files, mode }] of Object.entries(CONTENT_MIGRATIONS)) {
  const update = mode === "update";
  let sql = update
    ? `-- Updated guides for the studio site: ${title}.
-- Generated by scripts/content-sql.mjs from content/guides/*.json — edit those, not this file.
-- Adds new guides and replaces the ones nobody has edited in the admin (updated_by is null);
-- anything an editor changed is left alone. Replaced versions stay in each guide's revision history.

insert into public.ad_settings (id) values (1) on conflict (id) do nothing;
`
    : `-- Starter content for the studio site: ${title}, their guide categories and guides.
-- Generated by scripts/content-sql.mjs from content/guides/*.json — edit those, not this file.
-- Safe on a database that already has content: existing products, categories and guides are left alone.

insert into public.ad_settings (id) values (1) on conflict (id) do nothing;
`;

  for (const file of files) {
    const d = JSON.parse(readFileSync(`content/guides/${file}`, "utf8"));
    const p = d.product;
    const cols = [p.slug, p.name, p.kind, p.headline, p.headline_em, p.headline_style, p.description].map(q);
    const rest = [p.cta_label, p.cta_url, p.site_url, p.accent_dark, p.accent_light, p.button_dark, p.button_light].map(q);
    sql += `
-- ${p.name} ---------------------------------------------------------------
insert into public.products (slug, name, kind, headline, headline_em, headline_style, description, highlights, cta_label, cta_url, site_url, accent_dark, accent_light, button_dark, button_light, status, sort_order)
values (${cols.join(", ")}, ${q(JSON.stringify(p.highlights))}::jsonb, ${rest.join(", ")}, 'live', ${Number(p.sort_order)})
on conflict (slug) do ${
      update
        ? `update set name = excluded.name, kind = excluded.kind, headline = excluded.headline, headline_em = excluded.headline_em, headline_style = excluded.headline_style,
  description = excluded.description, highlights = excluded.highlights, cta_label = excluded.cta_label, cta_url = excluded.cta_url, site_url = excluded.site_url,
  accent_dark = excluded.accent_dark, accent_light = excluded.accent_light, button_dark = excluded.button_dark, button_light = excluded.button_light
  where public.products.updated_by is null`
        : "nothing"
    };

insert into public.categories (product_id, name, slug, sort_order)
select p.id, c.name, c.slug, c.ord from public.products p
cross join (values ${d.categories.map((c, i) => `(${q(c.name)}, ${q(c.slug)}, ${i + 1})`).join(", ")}) as c(name, slug, ord)
where p.slug = ${q(p.slug)}
on conflict (product_id, slug) do ${update ? "update set name = excluded.name, sort_order = excluded.sort_order" : "nothing"};
`;
    for (const g of d.guides) {
      sql += `
insert into public.guides (product_id, category_id, slug, title, standfirst, blocks, start_here, meta_title, meta_description, author_name, status)
select p.id, c.id, ${q(g.slug)}, ${q(g.title)}, ${q(g.standfirst)}, ${q(JSON.stringify(g.blocks))}::jsonb, ${g.start_here ? "true" : "false"}, ${q(g.meta_title)}, ${q(g.meta_description)}, 'Midnight Poetry Studio', 'published'
from public.products p join public.categories c on c.product_id = p.id and c.slug = ${q(g.category)}
where p.slug = ${q(p.slug)}
on conflict (product_id, slug) do ${
        update
          ? `update set category_id = excluded.category_id, title = excluded.title, standfirst = excluded.standfirst, blocks = excluded.blocks, start_here = excluded.start_here,
  meta_title = excluded.meta_title, meta_description = excluded.meta_description
  where public.guides.updated_by is null`
          : "nothing"
      };
`;
    }
  }
  writeFileSync(OUT, sql);
  console.log(`wrote ${OUT}`);
}
